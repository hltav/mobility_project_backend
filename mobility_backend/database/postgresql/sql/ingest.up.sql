CREATE TABLE ingest.feed_sources (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
 provider text NOT NULL, name text NOT NULL, source_kind text NOT NULL CHECK (source_kind IN ('gtfs_schedule','sptrans')),
 source_uri_reference text, profile_version text NOT NULL, default_timezone text,
 created_at timestamptz(6), updated_at timestamptz(6), UNIQUE(provider,name), UNIQUE(id,source_kind)
);
CREATE TABLE ingest.feed_versions (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
 feed_source_id bigint NOT NULL REFERENCES ingest.feed_sources(id),
 checksum_sha256 char(64) NOT NULL CHECK (checksum_sha256 ~ '^[0-9a-f]{64}$'),
 normalizer_version text NOT NULL, profile_version text NOT NULL,
 acquisition_at timestamptz(6), declared_start date, declared_end date,
 state text NOT NULL DEFAULT 'staging' CHECK (state IN ('staging','validating','ready','failed')),
 counts_manifest jsonb NOT NULL DEFAULT '{}', validated_at timestamptz(6),
 created_at timestamptz(6), updated_at timestamptz(6),
 UNIQUE(feed_source_id,checksum_sha256,normalizer_version,profile_version), UNIQUE(feed_source_id,id),
 CHECK (declared_end >= declared_start), CHECK (state <> 'ready' OR validated_at IS NOT NULL)
);
CREATE TABLE ingest.feed_publications (
 feed_source_id bigint PRIMARY KEY REFERENCES ingest.feed_sources(id), active_feed_version_id bigint,
 generation bigint NOT NULL DEFAULT 0 CHECK (generation >= 0), updated_at timestamptz(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(feed_source_id,active_feed_version_id) REFERENCES ingest.feed_versions(feed_source_id,id)
);
CREATE INDEX feed_publications_version_idx ON ingest.feed_publications(active_feed_version_id);
CREATE INDEX feed_publications_source_version_idx ON ingest.feed_publications(feed_source_id,active_feed_version_id);
CREATE TABLE ingest.feed_promotion_events (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
 feed_source_id bigint NOT NULL REFERENCES ingest.feed_sources(id), previous_version_id bigint, new_version_id bigint NOT NULL,
 generation bigint NOT NULL CHECK (generation > 0), actor_reference text NOT NULL, reason text NOT NULL,
 promoted_at timestamptz(6) NOT NULL DEFAULT CURRENT_TIMESTAMP, UNIQUE(feed_source_id,generation),
 FOREIGN KEY(feed_source_id,previous_version_id) REFERENCES ingest.feed_versions(feed_source_id,id),
 FOREIGN KEY(feed_source_id,new_version_id) REFERENCES ingest.feed_versions(feed_source_id,id)
);
CREATE INDEX feed_events_previous_idx ON ingest.feed_promotion_events(feed_source_id,previous_version_id);
CREATE INDEX feed_events_new_idx ON ingest.feed_promotion_events(feed_source_id,new_version_id);
CREATE TABLE ingest.import_runs (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
 feed_version_id bigint NOT NULL REFERENCES ingest.feed_versions(id),
 state text NOT NULL DEFAULT 'running' CHECK (state IN ('running','succeeded','failed','cancelled')),
 started_at timestamptz(6) NOT NULL DEFAULT CURRENT_TIMESTAMP, finished_at timestamptz(6),
 checkpoint_manifest jsonb NOT NULL DEFAULT '{}', row_counts jsonb NOT NULL DEFAULT '{}', error_code text,
 created_at timestamptz(6), updated_at timestamptz(6), CHECK (finished_at >= started_at), UNIQUE(feed_version_id,id)
);
CREATE INDEX import_runs_version_idx ON ingest.import_runs(feed_version_id);
CREATE TABLE ingest.import_rejections (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
 import_run_id bigint NOT NULL REFERENCES ingest.import_runs(id), entity text NOT NULL, file_reference text,
 reason_code text NOT NULL, row_number bigint CHECK (row_number > 0), source_pk text, protected_raw_reference text,
 rejected_at timestamptz(6) NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX import_rejections_run_idx ON ingest.import_rejections(import_run_id);
CREATE TABLE ingest.validation_results (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
 feed_version_id bigint NOT NULL REFERENCES ingest.feed_versions(id), import_run_id bigint,
 validator_version text NOT NULL, rule_code text NOT NULL, severity text NOT NULL CHECK (severity IN ('error','warning','info')),
 passed boolean NOT NULL, details jsonb NOT NULL DEFAULT '{}', checked_at timestamptz(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(feed_version_id,import_run_id) REFERENCES ingest.import_runs(feed_version_id,id)
);
CREATE INDEX validation_results_feed_idx ON ingest.validation_results(feed_version_id);
CREATE INDEX validation_results_run_idx ON ingest.validation_results(feed_version_id,import_run_id);
