CREATE TABLE public.users (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
 name varchar(255) NOT NULL, email public.citext NOT NULL UNIQUE CHECK (length(email) <= 255),
 password varchar(255), remember_token varchar(100),
 email_verified_at timestamptz(6), google_id varchar(255) UNIQUE, avatar varchar(255),
 created_at timestamptz(6), updated_at timestamptz(6)
);
CREATE INDEX users_name_idx ON public.users(name);
CREATE TABLE public.password_reset_tokens (
 email public.citext PRIMARY KEY CHECK (length(email) <= 255), token varchar(255) NOT NULL, created_at timestamptz(6)
);
CREATE TABLE public.sessions (
 id varchar(255) PRIMARY KEY, user_id bigint REFERENCES public.users(id) ON DELETE SET NULL,
 ip_address varchar(45), user_agent text, payload text NOT NULL, last_activity bigint NOT NULL CHECK (last_activity >= 0)
);
CREATE INDEX sessions_user_idx ON public.sessions(user_id);
CREATE INDEX sessions_activity_idx ON public.sessions(last_activity);
CREATE TABLE public.personal_access_tokens (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
 tokenable_type varchar(255) NOT NULL, tokenable_id bigint NOT NULL CHECK (tokenable_id > 0),
 name text NOT NULL, token varchar(64) NOT NULL UNIQUE, abilities text,
 last_used_at timestamptz(6), expires_at timestamptz(6), created_at timestamptz(6), updated_at timestamptz(6)
);
CREATE INDEX personal_access_tokens_owner_idx ON public.personal_access_tokens(tokenable_type,tokenable_id);
CREATE INDEX personal_access_tokens_expiry_idx ON public.personal_access_tokens(expires_at);
CREATE TABLE public.cache (key varchar(255) PRIMARY KEY, value text NOT NULL, expiration bigint NOT NULL);
CREATE INDEX cache_expiration_idx ON public.cache(expiration);
CREATE TABLE public.cache_locks (key varchar(255) PRIMARY KEY, owner varchar(255) NOT NULL, expiration bigint NOT NULL);
CREATE INDEX cache_locks_expiration_idx ON public.cache_locks(expiration);
CREATE TABLE public.jobs (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0), queue varchar(255) NOT NULL,
 payload text NOT NULL, attempts integer NOT NULL CHECK (attempts >= 0),
 reserved_at bigint CHECK (reserved_at >= 0), available_at bigint NOT NULL CHECK (available_at >= 0),
 created_at bigint NOT NULL CHECK (created_at >= 0)
);
CREATE INDEX jobs_queue_idx ON public.jobs(queue);
CREATE TABLE public.job_batches (
 id varchar(255) PRIMARY KEY, name varchar(255) NOT NULL,
 total_jobs integer NOT NULL CHECK (total_jobs >= 0), pending_jobs integer NOT NULL CHECK (pending_jobs >= 0),
 failed_jobs integer NOT NULL CHECK (failed_jobs >= 0), failed_job_ids text NOT NULL, options text,
 cancelled_at bigint, created_at bigint NOT NULL, finished_at bigint
);
CREATE TABLE public.failed_jobs (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0), uuid varchar(255) NOT NULL UNIQUE,
 connection text NOT NULL, queue text NOT NULL, payload text NOT NULL, exception text NOT NULL,
 failed_at timestamptz(6) NOT NULL DEFAULT CURRENT_TIMESTAMP
);
