-- Stage 3: explicit recovery and reconciliation for chunked snapshots, never automatic startup DDL.
CREATE TABLE ingest.feed_recovery_events (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK(id>0),
 feed_version_id bigint NOT NULL REFERENCES ingest.feed_versions(id), previous_run_id bigint,
 previous_state text NOT NULL CHECK(previous_state IN ('staging','validating','failed')),
 actor_reference text NOT NULL, reason text NOT NULL, recovered_at timestamptz(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(feed_version_id,previous_run_id) REFERENCES ingest.import_runs(feed_version_id,id)
);
CREATE INDEX recovery_feed_run_idx ON ingest.feed_recovery_events(feed_version_id,previous_run_id);
GRANT SELECT ON ingest.feed_recovery_events TO mobility_importer;

CREATE FUNCTION ingest.assert_snapshot_counts(p_feed bigint,p_expected jsonb) RETURNS void LANGUAGE plpgsql SET search_path=pg_catalog AS $$
DECLARE t text; expected bigint; actual bigint;
BEGIN
 IF jsonb_typeof(p_expected) IS DISTINCT FROM 'object' THEN RAISE EXCEPTION 'Expected counts must be an object' USING ERRCODE='23514'; END IF;
 IF (SELECT count(*) FROM jsonb_object_keys(p_expected))<>13 THEN
  RAISE EXCEPTION 'Complete expected table counts required' USING ERRCODE='23514';
 END IF;
 FOREACH t IN ARRAY ARRAY['agencies','routes','stops','services','calendars','service_exceptions','shapes','shape_points','journey_patterns','journey_pattern_stops','trips','stop_times','frequencies'] LOOP
  IF NOT (p_expected ? t) OR (p_expected->>t)!~'^[0-9]+$' THEN RAISE EXCEPTION 'Invalid expected count' USING ERRCODE='23514'; END IF;
  expected:=(p_expected->>t)::bigint;
  EXECUTE format('SELECT count(*) FROM gtfs.%I WHERE feed_version_id=$1',t) INTO actual USING p_feed;
  IF actual<>expected THEN RAISE EXCEPTION 'Snapshot row count mismatch in %',t USING ERRCODE='23514'; END IF;
 END LOOP;
 IF EXISTS(SELECT 1 FROM gtfs.shapes WHERE feed_version_id=p_feed AND (geometry_status<>'valid' OR path_geom IS NULL))
 OR EXISTS(SELECT 1 FROM gtfs.trips WHERE feed_version_id=p_feed AND pattern_id IS NULL) THEN
  RAISE EXCEPTION 'Incomplete shape/pattern materialization' USING ERRCODE='23514';
 END IF;
 IF EXISTS(SELECT 1 FROM gtfs.trips t JOIN gtfs.journey_patterns p ON (p.feed_version_id,p.id)=(t.feed_version_id,t.pattern_id)
  WHERE t.feed_version_id=p_feed AND (t.gtfs_direction_id IS DISTINCT FROM p.gtfs_direction_id OR t.shape_id IS DISTINCT FROM p.shape_id)) THEN
  RAISE EXCEPTION 'Trip/pattern identity differs' USING ERRCODE='23514';
 END IF;
 IF EXISTS(SELECT 1 FROM gtfs.stop_times s JOIN gtfs.trips t ON(t.feed_version_id,t.id)=(s.feed_version_id,s.trip_id)
  LEFT JOIN gtfs.journey_pattern_stops p ON(p.feed_version_id,p.pattern_id,p.pattern_sequence)=(s.feed_version_id,t.pattern_id,s.stop_sequence)
  WHERE s.feed_version_id=p_feed AND (p.id IS NULL OR p.gtfs_stop_pk<>s.gtfs_stop_pk OR p.pickup_type IS DISTINCT FROM s.pickup_type OR p.drop_off_type IS DISTINCT FROM s.drop_off_type)) THEN
  RAISE EXCEPTION 'Trip occurrences differ from pattern' USING ERRCODE='23514';
 END IF;
END $$;
REVOKE ALL ON FUNCTION ingest.assert_snapshot_counts(bigint,jsonb) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION ingest.assert_snapshot_counts(bigint,jsonb) TO mobility_importer;

CREATE OR REPLACE FUNCTION ingest.guard_feed_transition() RETURNS trigger LANGUAGE plpgsql SET search_path = pg_catalog AS $$
BEGIN
 IF TG_OP = 'DELETE' THEN RAISE EXCEPTION 'Feed deletion is not a runtime operation' USING ERRCODE = '55000'; END IF;
 IF TG_OP = 'INSERT' THEN
  IF NEW.state <> 'staging' THEN RAISE EXCEPTION 'New feeds must start in staging' USING ERRCODE = '55000'; END IF;
  RETURN NEW;
 END IF;
 IF OLD.state='ready' THEN RAISE EXCEPTION 'Ready feed versions are immutable' USING ERRCODE='55000'; END IF;
 IF OLD.state IN ('failed','validating') AND NEW.state='staging' THEN
  IF current_user <> pg_catalog.pg_get_userbyid((SELECT relowner FROM pg_catalog.pg_class WHERE oid='ingest.feed_versions'::regclass)) THEN
   RAISE EXCEPTION 'Use the explicit recovery function' USING ERRCODE='42501';
  END IF;
  IF NEW.feed_source_id<>OLD.feed_source_id OR NEW.checksum_sha256<>OLD.checksum_sha256 OR NEW.normalizer_version<>OLD.normalizer_version OR NEW.profile_version<>OLD.profile_version THEN
   RAISE EXCEPTION 'Recovery cannot change feed identity' USING ERRCODE='23514';
  END IF;
  RETURN NEW;
 END IF;
 IF OLD.state='failed' THEN RAISE EXCEPTION 'Failed feed requires explicit recovery' USING ERRCODE='55000'; END IF;
 IF NEW.feed_source_id <> OLD.feed_source_id OR NEW.checksum_sha256 <> OLD.checksum_sha256
    OR NEW.normalizer_version <> OLD.normalizer_version OR NEW.profile_version <> OLD.profile_version THEN
  RAISE EXCEPTION 'Feed identity is immutable' USING ERRCODE = '55000';
 END IF;
 IF NEW.state <> OLD.state AND NOT ((OLD.state = 'staging' AND NEW.state IN ('validating','failed'))
    OR (OLD.state = 'validating' AND NEW.state IN ('ready','failed'))) THEN
  RAISE EXCEPTION 'Invalid feed state transition' USING ERRCODE = '55000';
 END IF;
 IF NEW.state = 'ready' AND OLD.state <> 'ready' THEN
  IF NEW.profile_version='open-transit.schedule.stage3.v1' THEN
   PERFORM ingest.assert_snapshot_counts(NEW.id,NEW.counts_manifest->'expected_table_rows');
  END IF;
  -- Profile validation and SQL integrity gates must both pass.
  IF NOT EXISTS (SELECT 1 FROM ingest.validation_results WHERE feed_version_id = NEW.id AND rule_code = 'profile.complete' AND passed AND severity = 'info')
    OR EXISTS (SELECT 1 FROM ingest.validation_results WHERE feed_version_id = NEW.id AND severity = 'error' AND NOT passed)
    OR NOT EXISTS (SELECT 1 FROM ingest.import_runs WHERE feed_version_id = NEW.id AND state = 'succeeded') THEN
   RAISE EXCEPTION 'Successful import and profile validation required' USING ERRCODE = '23514';
  END IF;
  IF EXISTS (SELECT 1 FROM gtfs.services s LEFT JOIN gtfs.calendars c ON (c.feed_version_id,c.service_id) = (s.feed_version_id,s.id)
       WHERE s.feed_version_id = NEW.id AND (s.has_weekly_calendar <> (c.service_id IS NOT NULL)
       OR (NOT s.has_weekly_calendar AND NOT EXISTS (SELECT 1 FROM gtfs.service_exceptions e WHERE (e.feed_version_id,e.service_id) = (s.feed_version_id,s.id))))) THEN
   RAISE EXCEPTION 'Service calendar or exception coverage is inconsistent' USING ERRCODE = '23514';
  END IF;
  IF EXISTS (SELECT 1 FROM (SELECT start_service_seconds,
       max(end_service_seconds) OVER (PARTITION BY trip_id ORDER BY start_service_seconds ROWS BETWEEN UNBOUNDED PRECEDING AND 1 PRECEDING) AS prior_end
       FROM gtfs.frequencies WHERE feed_version_id=NEW.id) f WHERE start_service_seconds<prior_end) THEN
   RAISE EXCEPTION 'Frequency intervals overlap' USING ERRCODE = '23514';
  END IF;
  IF EXISTS (SELECT 1 FROM (SELECT coalesce(arrival_service_seconds,departure_service_seconds) AS current_seconds,
       max(coalesce(departure_service_seconds,arrival_service_seconds)) OVER (PARTITION BY trip_id ORDER BY stop_sequence ROWS BETWEEN UNBOUNDED PRECEDING AND 1 PRECEDING) AS prior_time
       FROM gtfs.stop_times WHERE feed_version_id=NEW.id) s WHERE s.current_seconds<s.prior_time) THEN
   RAISE EXCEPTION 'Service time decreases along trip' USING ERRCODE = '23514';
  END IF;
  IF EXISTS (SELECT 1 FROM gtfs.trips t JOIN gtfs.journey_patterns p ON (p.feed_version_id,p.id)=(t.feed_version_id,t.pattern_id)
       WHERE t.feed_version_id=NEW.id AND ((t.gtfs_direction_id IS NOT NULL AND p.gtfs_direction_id IS NOT NULL AND t.gtfs_direction_id<>p.gtfs_direction_id)
       OR (t.shape_id IS NOT NULL AND p.shape_id IS NOT NULL AND t.shape_id<>p.shape_id))) THEN
   RAISE EXCEPTION 'Trip direction or shape differs from pattern' USING ERRCODE='23514';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM gtfs.agencies WHERE feed_version_id=NEW.id)
     OR NOT EXISTS (SELECT 1 FROM gtfs.routes WHERE feed_version_id=NEW.id)
     OR NOT EXISTS (SELECT 1 FROM gtfs.stops WHERE feed_version_id=NEW.id)
     OR NOT EXISTS (SELECT 1 FROM gtfs.trips WHERE feed_version_id=NEW.id)
     OR NOT EXISTS (SELECT 1 FROM gtfs.stop_times WHERE feed_version_id=NEW.id) THEN
   RAISE EXCEPTION 'Schedule baseline is empty' USING ERRCODE = '23514';
  END IF;
  NEW.validated_at := CURRENT_TIMESTAMP;
 END IF;
 RETURN NEW;
END $$;

CREATE FUNCTION ingest.recover_feed(p_feed bigint,p_checksum text,p_normalizer text,p_profile text,p_actor text,p_reason text)
 RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path=pg_catalog AS $$
DECLARE v ingest.feed_versions%ROWTYPE; prior ingest.import_runs%ROWTYPE; checkpoint jsonb;
BEGIN
 IF nullif(btrim(p_actor),'') IS NULL OR nullif(btrim(p_reason),'') IS NULL THEN RAISE EXCEPTION 'Recovery actor and reason required' USING ERRCODE='22023'; END IF;
 IF NOT pg_try_advisory_xact_lock(hashtextextended('ingest:feed:'||p_feed::text,0)) THEN
  RAISE EXCEPTION 'Feed writer is still active' USING ERRCODE='55000';
 END IF;
 SELECT * INTO STRICT v FROM ingest.feed_versions WHERE id=p_feed FOR UPDATE;
 IF p_checksum IS DISTINCT FROM v.checksum_sha256::text OR p_normalizer IS DISTINCT FROM v.normalizer_version OR p_profile IS DISTINCT FROM v.profile_version THEN
  RAISE EXCEPTION 'Recovery identity mismatch' USING ERRCODE='23514';
 END IF;
 IF v.state NOT IN ('staging','validating','failed') OR EXISTS(SELECT 1 FROM ingest.feed_publications WHERE active_feed_version_id=p_feed) THEN
  RAISE EXCEPTION 'Published/ready feed cannot be recovered' USING ERRCODE='55000';
 END IF;
 SELECT * INTO prior FROM ingest.import_runs WHERE feed_version_id=p_feed ORDER BY id DESC LIMIT 1;
 checkpoint:=coalesce(prior.checkpoint_manifest,'{}'::jsonb);
 UPDATE ingest.import_runs SET state='failed',finished_at=clock_timestamp(),error_code='interrupted_run',updated_at=clock_timestamp()
  WHERE feed_version_id=p_feed AND state='running';
 UPDATE ingest.feed_versions SET state='staging',validated_at=NULL,updated_at=clock_timestamp() WHERE id=p_feed;
 INSERT INTO ingest.feed_recovery_events(feed_version_id,previous_run_id,previous_state,actor_reference,reason)
  VALUES(p_feed,prior.id,v.state,p_actor,p_reason);
 RETURN checkpoint;
END $$;
REVOKE ALL ON FUNCTION ingest.recover_feed(bigint,text,text,text,text,text) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION ingest.recover_feed(bigint,text,text,text,text,text) TO mobility_importer;
