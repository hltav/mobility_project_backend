CREATE TABLE gtfs.agencies (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
 feed_version_id bigint NOT NULL REFERENCES ingest.feed_versions(id), gtfs_agency_id text,
 name text NOT NULL, url text, timezone text NOT NULL, language text, raw_attributes jsonb,
 created_at timestamptz(6), updated_at timestamptz(6),
 UNIQUE(feed_version_id,id), UNIQUE NULLS NOT DISTINCT(feed_version_id,gtfs_agency_id)
);
CREATE TABLE gtfs.routes (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
 feed_version_id bigint NOT NULL REFERENCES ingest.feed_versions(id), agency_id bigint NOT NULL,
 gtfs_route_id text NOT NULL CHECK (gtfs_route_id <> ''), short_name text, long_name text,
 route_type integer NOT NULL CHECK (route_type >= 0), color_hex varchar(6), text_color_hex varchar(6), raw_attributes jsonb,
 created_at timestamptz(6), updated_at timestamptz(6), UNIQUE(feed_version_id,id), UNIQUE(feed_version_id,gtfs_route_id),
 FOREIGN KEY(feed_version_id,agency_id) REFERENCES gtfs.agencies(feed_version_id,id),
 CHECK (nullif(short_name,'') IS NOT NULL OR nullif(long_name,'') IS NOT NULL),
 CHECK (color_hex ~ '^[0-9A-Fa-f]{6}$'), CHECK (text_color_hex ~ '^[0-9A-Fa-f]{6}$')
);
CREATE INDEX gtfs_routes_agency_idx ON gtfs.routes(feed_version_id,agency_id);
CREATE TABLE gtfs.stops (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
 feed_version_id bigint NOT NULL REFERENCES ingest.feed_versions(id), gtfs_stop_id text NOT NULL CHECK (gtfs_stop_id <> ''),
 stop_code text, name text, description text, location_type smallint NOT NULL DEFAULT 0 CHECK (location_type BETWEEN 0 AND 4),
 parent_gtfs_stop_pk bigint, timezone text, zone_id text, wheelchair_boarding smallint CHECK (wheelchair_boarding IN (0,1,2)),
 position_geom public.geometry(Point,4326),
 position_geog public.geography(Point,4326) GENERATED ALWAYS AS (position_geom::public.geography) STORED,
 raw_attributes jsonb, created_at timestamptz(6), updated_at timestamptz(6),
 UNIQUE(feed_version_id,id), UNIQUE(feed_version_id,gtfs_stop_id), UNIQUE(feed_version_id,id,gtfs_stop_id),
 FOREIGN KEY(feed_version_id,parent_gtfs_stop_pk) REFERENCES gtfs.stops(feed_version_id,id) DEFERRABLE INITIALLY DEFERRED,
 CHECK (parent_gtfs_stop_pk IS NULL OR parent_gtfs_stop_pk <> id),
 CHECK (position_geom IS NULL OR (NOT public.ST_IsEmpty(position_geom) AND public.ST_X(position_geom) BETWEEN -180 AND 180 AND public.ST_Y(position_geom) BETWEEN -90 AND 90)),
 CHECK (location_type NOT IN (0,1,2) OR (position_geom IS NOT NULL AND nullif(name,'') IS NOT NULL)),
 CHECK (location_type NOT IN (2,3,4) OR parent_gtfs_stop_pk IS NOT NULL)
);
CREATE INDEX gtfs_stops_parent_idx ON gtfs.stops(feed_version_id,parent_gtfs_stop_pk);
CREATE INDEX gtfs_stops_geog_gist ON gtfs.stops USING gist(position_geog);
CREATE INDEX gtfs_stops_geom_gist ON gtfs.stops USING gist(position_geom);
CREATE TABLE gtfs.services (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
 feed_version_id bigint NOT NULL REFERENCES ingest.feed_versions(id), gtfs_service_id text NOT NULL CHECK (gtfs_service_id <> ''),
 has_weekly_calendar boolean NOT NULL, created_at timestamptz(6), updated_at timestamptz(6),
 UNIQUE(feed_version_id,id), UNIQUE(feed_version_id,gtfs_service_id)
);
-- Separate weekly calendar permits services defined solely by calendar_dates.txt.
CREATE TABLE gtfs.calendars (
 feed_version_id bigint NOT NULL, service_id bigint NOT NULL,
 monday boolean NOT NULL, tuesday boolean NOT NULL, wednesday boolean NOT NULL, thursday boolean NOT NULL,
 friday boolean NOT NULL, saturday boolean NOT NULL, sunday boolean NOT NULL,
 start_date date NOT NULL, end_date date NOT NULL CHECK (end_date >= start_date), raw_attributes jsonb,
 PRIMARY KEY(feed_version_id,service_id), FOREIGN KEY(feed_version_id,service_id) REFERENCES gtfs.services(feed_version_id,id)
);
CREATE TABLE gtfs.service_exceptions (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
 feed_version_id bigint NOT NULL, service_id bigint NOT NULL, service_date date NOT NULL,
 exception_type smallint NOT NULL CHECK (exception_type IN (1,2)), raw_date varchar(8), raw_attributes jsonb,
 UNIQUE(feed_version_id,id), UNIQUE(feed_version_id,service_id,service_date),
 FOREIGN KEY(feed_version_id,service_id) REFERENCES gtfs.services(feed_version_id,id)
);
CREATE TABLE gtfs.shapes (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
 feed_version_id bigint NOT NULL REFERENCES ingest.feed_versions(id), gtfs_shape_id text NOT NULL CHECK (gtfs_shape_id <> ''),
 path_geom public.geometry(LineString,4326), source_distance_unit text,
 geometry_status text NOT NULL DEFAULT 'pending' CHECK (geometry_status IN ('pending','valid','invalid','unavailable')),
 fingerprint_sha256 char(64) CHECK (fingerprint_sha256 ~ '^[0-9a-f]{64}$'),
 created_at timestamptz(6), updated_at timestamptz(6), UNIQUE(feed_version_id,id), UNIQUE(feed_version_id,gtfs_shape_id),
 CHECK (path_geom IS NULL OR (NOT public.ST_IsEmpty(path_geom) AND public.ST_NPoints(path_geom) >= 2 AND public.ST_IsValid(path_geom)
 AND public.ST_XMin(public.Box3D(path_geom)) >= -180 AND public.ST_XMax(public.Box3D(path_geom)) <= 180
 AND public.ST_YMin(public.Box3D(path_geom)) >= -90 AND public.ST_YMax(public.Box3D(path_geom)) <= 90)),
 CHECK (geometry_status <> 'valid' OR path_geom IS NOT NULL)
);
CREATE INDEX gtfs_shapes_geom_gist ON gtfs.shapes USING gist(path_geom);
CREATE TABLE gtfs.shape_points (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
 feed_version_id bigint NOT NULL, shape_id bigint NOT NULL, shape_point_sequence integer NOT NULL CHECK (shape_point_sequence >= 0),
 latitude numeric(10,7) NOT NULL CHECK (latitude BETWEEN -90 AND 90), longitude numeric(10,7) NOT NULL CHECK (longitude BETWEEN -180 AND 180),
 source_shape_distance numeric CHECK (source_shape_distance >= 0), derived_distance_m double precision CHECK (derived_distance_m >= 0 AND derived_distance_m < 'Infinity'::float8), raw_attributes jsonb,
 UNIQUE(feed_version_id,id), UNIQUE(feed_version_id,shape_id,shape_point_sequence),
 FOREIGN KEY(feed_version_id,shape_id) REFERENCES gtfs.shapes(feed_version_id,id)
);
CREATE TABLE gtfs.journey_patterns (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
 feed_version_id bigint NOT NULL, route_id bigint NOT NULL, gtfs_direction_id smallint CHECK (gtfs_direction_id IN (0,1)),
 shape_id bigint, headsign text, fingerprint_sha256 char(64) NOT NULL CHECK (fingerprint_sha256 ~ '^[0-9a-f]{64}$'),
 created_at timestamptz(6), updated_at timestamptz(6), UNIQUE(feed_version_id,id), UNIQUE(feed_version_id,route_id,id), UNIQUE(feed_version_id,fingerprint_sha256),
 FOREIGN KEY(feed_version_id,route_id) REFERENCES gtfs.routes(feed_version_id,id),
 FOREIGN KEY(feed_version_id,shape_id) REFERENCES gtfs.shapes(feed_version_id,id)
);
CREATE INDEX gtfs_patterns_shape_idx ON gtfs.journey_patterns(feed_version_id,shape_id);
CREATE TABLE gtfs.journey_pattern_stops (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
 feed_version_id bigint NOT NULL, pattern_id bigint NOT NULL, pattern_sequence integer NOT NULL CHECK (pattern_sequence >= 0),
 gtfs_stop_pk bigint NOT NULL, pickup_type smallint CHECK (pickup_type IN (0,1,2,3)), drop_off_type smallint CHECK (drop_off_type IN (0,1,2,3)),
 source_shape_distance numeric CHECK (source_shape_distance >= 0),
 UNIQUE(feed_version_id,id), UNIQUE(feed_version_id,pattern_id,pattern_sequence),
 FOREIGN KEY(feed_version_id,pattern_id) REFERENCES gtfs.journey_patterns(feed_version_id,id),
 FOREIGN KEY(feed_version_id,gtfs_stop_pk) REFERENCES gtfs.stops(feed_version_id,id)
);
CREATE INDEX gtfs_pattern_stops_stop_idx ON gtfs.journey_pattern_stops(feed_version_id,gtfs_stop_pk);
CREATE TABLE gtfs.trips (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
 feed_version_id bigint NOT NULL, route_id bigint NOT NULL, service_id bigint NOT NULL, pattern_id bigint, shape_id bigint,
 gtfs_trip_id text NOT NULL CHECK (gtfs_trip_id <> ''), gtfs_direction_id smallint CHECK (gtfs_direction_id IN (0,1)),
 headsign text, trip_short_name text, block_id text, wheelchair_accessible smallint CHECK (wheelchair_accessible IN (0,1,2)),
 bikes_allowed smallint CHECK (bikes_allowed IN (0,1,2)), raw_attributes jsonb,
 created_at timestamptz(6), updated_at timestamptz(6), UNIQUE(feed_version_id,id), UNIQUE(feed_version_id,gtfs_trip_id),
 FOREIGN KEY(feed_version_id,route_id) REFERENCES gtfs.routes(feed_version_id,id),
 FOREIGN KEY(feed_version_id,service_id) REFERENCES gtfs.services(feed_version_id,id),
 FOREIGN KEY(feed_version_id,route_id,pattern_id) REFERENCES gtfs.journey_patterns(feed_version_id,route_id,id),
 FOREIGN KEY(feed_version_id,shape_id) REFERENCES gtfs.shapes(feed_version_id,id)
);
CREATE INDEX gtfs_trips_service_idx ON gtfs.trips(feed_version_id,service_id);
CREATE INDEX gtfs_trips_pattern_idx ON gtfs.trips(feed_version_id,route_id,pattern_id);
CREATE INDEX gtfs_trips_shape_idx ON gtfs.trips(feed_version_id,shape_id);
CREATE TABLE gtfs.stop_times (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
 feed_version_id bigint NOT NULL, trip_id bigint NOT NULL, gtfs_stop_pk bigint NOT NULL,
 stop_sequence integer NOT NULL CHECK (stop_sequence >= 0),
 arrival_service_seconds integer CHECK (arrival_service_seconds >= 0), departure_service_seconds integer CHECK (departure_service_seconds >= 0),
 raw_arrival_time text, raw_departure_time text, stop_headsign text,
 pickup_type smallint CHECK (pickup_type IN (0,1,2,3)), drop_off_type smallint CHECK (drop_off_type IN (0,1,2,3)),
 timepoint smallint CHECK (timepoint IN (0,1)), source_shape_distance numeric CHECK (source_shape_distance >= 0), raw_attributes jsonb,
 created_at timestamptz(6), updated_at timestamptz(6), UNIQUE(feed_version_id,id), UNIQUE(feed_version_id,trip_id,stop_sequence),
 FOREIGN KEY(feed_version_id,trip_id) REFERENCES gtfs.trips(feed_version_id,id),
 FOREIGN KEY(feed_version_id,gtfs_stop_pk) REFERENCES gtfs.stops(feed_version_id,id),
 CHECK (departure_service_seconds >= arrival_service_seconds)
);
CREATE INDEX gtfs_stop_times_stop_idx ON gtfs.stop_times(feed_version_id,gtfs_stop_pk);
CREATE TABLE gtfs.frequencies (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
 feed_version_id bigint NOT NULL, trip_id bigint NOT NULL,
 start_service_seconds integer NOT NULL CHECK (start_service_seconds >= 0),
 end_service_seconds integer NOT NULL, headway_seconds integer NOT NULL CHECK (headway_seconds > 0),
 exact_times smallint NOT NULL CHECK (exact_times IN (0,1)), raw_exact_times text, raw_attributes jsonb,
 created_at timestamptz(6), updated_at timestamptz(6), UNIQUE(feed_version_id,id), UNIQUE(feed_version_id,trip_id,start_service_seconds),
 FOREIGN KEY(feed_version_id,trip_id) REFERENCES gtfs.trips(feed_version_id,id), CHECK (end_service_seconds > start_service_seconds)
);
