CREATE TABLE public.lines (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
 provider varchar(32) NOT NULL DEFAULT 'sptrans', sptrans_line_id bigint CHECK (sptrans_line_id > 0),
 code_prefix text, code_suffix integer CHECK (code_suffix >= 0), display_code varchar(255) NOT NULL, display_name varchar(255) NOT NULL,
 sptrans_direction smallint CHECK (sptrans_direction IN (1,2)), is_circular boolean,
 headsign_primary_to_secondary text, headsign_secondary_to_primary text, headsign text,
 origin_stop_id bigint, destination_stop_id bigint,
 origin_lat numeric(10,7) CHECK (origin_lat BETWEEN -90 AND 90), origin_lng numeric(10,7) CHECK (origin_lng BETWEEN -180 AND 180),
 destination_lat numeric(10,7) CHECK (destination_lat BETWEEN -90 AND 90), destination_lng numeric(10,7) CHECK (destination_lng BETWEEN -180 AND 180),
 -- Read-only HTTP compatibility aliases. Future writers must use canonical columns.
 code varchar(255) GENERATED ALWAYS AS (display_code) STORED,
 name varchar(255) GENERATED ALWAYS AS (display_name) STORED,
 sptrans_id bigint GENERATED ALWAYS AS (sptrans_line_id) STORED,
 circular boolean GENERATED ALWAYS AS (is_circular) STORED,
 origin text GENERATED ALWAYS AS (headsign_primary_to_secondary) STORED,
 destination text GENERATED ALWAYS AS (headsign_secondary_to_primary) STORED,
 created_at timestamptz(6), updated_at timestamptz(6),
 CHECK (sptrans_line_id IS NULL OR provider = 'sptrans'), CHECK (sptrans_direction IS NULL OR sptrans_line_id IS NOT NULL),
 CHECK ((origin_lat IS NULL) = (origin_lng IS NULL)), CHECK ((destination_lat IS NULL) = (destination_lng IS NULL))
);
CREATE UNIQUE INDEX lines_sptrans_identity_uq ON public.lines(provider,sptrans_line_id) WHERE sptrans_line_id IS NOT NULL;
CREATE INDEX lines_display_code_idx ON public.lines(display_code,id);
CREATE INDEX lines_code_idx ON public.lines(code);
CREATE INDEX lines_sptrans_compat_idx ON public.lines(sptrans_id);
CREATE TABLE public.bus_stops (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0), name varchar(255) NOT NULL,
 description text, address text, position_geom public.geometry(Point,4326),
 position_geog public.geography(Point,4326) GENERATED ALWAYS AS (position_geom::public.geography) STORED,
 latitude numeric(10,7) GENERATED ALWAYS AS (public.ST_Y(position_geom)::numeric(10,7)) STORED,
 longitude numeric(10,7) GENERATED ALWAYS AS (public.ST_X(position_geom)::numeric(10,7)) STORED,
 legacy_visible boolean NOT NULL DEFAULT false, attributes_provenance jsonb NOT NULL DEFAULT '{}',
 created_at timestamptz(6), updated_at timestamptz(6),
 CHECK (position_geom IS NULL OR (NOT public.ST_IsEmpty(position_geom) AND public.ST_X(position_geom) BETWEEN -180 AND 180 AND public.ST_Y(position_geom) BETWEEN -90 AND 90))
);
CREATE INDEX bus_stops_name_idx ON public.bus_stops(name);
CREATE INDEX bus_stops_geog_gist ON public.bus_stops USING gist(position_geog);
CREATE INDEX bus_stops_geom_gist ON public.bus_stops USING gist(position_geom);
ALTER TABLE public.lines ADD FOREIGN KEY(origin_stop_id) REFERENCES public.bus_stops(id);
ALTER TABLE public.lines ADD FOREIGN KEY(destination_stop_id) REFERENCES public.bus_stops(id);
CREATE INDEX lines_origin_stop_idx ON public.lines(origin_stop_id);
CREATE INDEX lines_destination_stop_idx ON public.lines(destination_stop_id);
CREATE TABLE public.favorites (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
 user_id bigint NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
 line_id bigint NOT NULL REFERENCES public.lines(id) ON DELETE CASCADE,
 created_at timestamptz(6), updated_at timestamptz(6), UNIQUE(user_id,line_id)
);
CREATE INDEX favorites_line_idx ON public.favorites(line_id);
CREATE TABLE public.bus_stop_line (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
 bus_stop_id bigint NOT NULL REFERENCES public.bus_stops(id) ON DELETE CASCADE,
 line_id bigint NOT NULL REFERENCES public.lines(id) ON DELETE CASCADE,
 created_at timestamptz(6), updated_at timestamptz(6), UNIQUE(bus_stop_id,line_id)
);
CREATE INDEX bus_stop_line_line_idx ON public.bus_stop_line(line_id,bus_stop_id);
CREATE TABLE public.stop_source_references (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0), stop_id bigint NOT NULL REFERENCES public.bus_stops(id),
 provider varchar(32) NOT NULL, source_kind text NOT NULL CHECK (source_kind IN ('sptrans','gtfs')),
 feed_version_id bigint, gtfs_stop_pk bigint, sptrans_stop_code bigint,
 external_stop_id text NOT NULL CHECK (external_stop_id <> ''),
 status text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','confirmed','rejected')),
 method text NOT NULL, confidence_score numeric(6,5) CHECK (confidence_score BETWEEN 0 AND 1), raw_attributes jsonb,
 created_at timestamptz(6), updated_at timestamptz(6),
 FOREIGN KEY(feed_version_id,gtfs_stop_pk,external_stop_id) REFERENCES gtfs.stops(feed_version_id,id,gtfs_stop_id),
 CHECK ((source_kind = 'sptrans' AND provider = 'sptrans' AND sptrans_stop_code > 0 AND sptrans_stop_code IS NOT NULL
         AND external_stop_id = sptrans_stop_code::text AND feed_version_id IS NULL AND gtfs_stop_pk IS NULL)
     OR (source_kind = 'gtfs' AND feed_version_id IS NOT NULL AND gtfs_stop_pk IS NOT NULL AND sptrans_stop_code IS NULL))
);
CREATE UNIQUE INDEX stop_source_sptrans_uq ON public.stop_source_references(provider,sptrans_stop_code) WHERE source_kind = 'sptrans';
CREATE UNIQUE INDEX stop_source_gtfs_uq ON public.stop_source_references(feed_version_id,gtfs_stop_pk) WHERE source_kind = 'gtfs';
CREATE INDEX stop_source_gtfs_fk_idx ON public.stop_source_references(feed_version_id,gtfs_stop_pk,external_stop_id);
CREATE INDEX stop_source_stop_idx ON public.stop_source_references(stop_id,status);
CREATE TABLE public.line_stop_sources (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0), line_id bigint NOT NULL REFERENCES public.lines(id),
 stop_id bigint NOT NULL REFERENCES public.bus_stops(id), source text NOT NULL CHECK (source IN ('sptrans','gtfs')),
 feed_version_id bigint REFERENCES ingest.feed_versions(id), external_line_id text NOT NULL, external_stop_id text NOT NULL,
 status text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','confirmed','rejected')),
 created_at timestamptz(6), updated_at timestamptz(6),
 UNIQUE NULLS NOT DISTINCT(line_id,stop_id,source,feed_version_id,external_line_id,external_stop_id),
 CHECK ((source = 'sptrans' AND feed_version_id IS NULL) OR (source = 'gtfs' AND feed_version_id IS NOT NULL))
);
CREATE INDEX line_stop_sources_stop_idx ON public.line_stop_sources(stop_id);
CREATE INDEX line_stop_sources_feed_idx ON public.line_stop_sources(feed_version_id);
CREATE TABLE public.line_route_mappings (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0), feed_version_id bigint NOT NULL,
 line_id bigint NOT NULL REFERENCES public.lines(id), route_id bigint NOT NULL, pattern_id bigint,
 gtfs_direction_id smallint CHECK (gtfs_direction_id IN (0,1)),
 confidence_score numeric(6,5) NOT NULL CHECK (confidence_score BETWEEN 0 AND 1), matching_method text NOT NULL,
 status text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','confirmed','rejected')),
 valid_from timestamptz(6), valid_until timestamptz(6), created_at timestamptz(6), updated_at timestamptz(6),
 FOREIGN KEY(feed_version_id,route_id) REFERENCES gtfs.routes(feed_version_id,id),
 FOREIGN KEY(feed_version_id,route_id,pattern_id) REFERENCES gtfs.journey_patterns(feed_version_id,route_id,id),
 UNIQUE NULLS NOT DISTINCT(feed_version_id,line_id,route_id,pattern_id,gtfs_direction_id), CHECK (valid_until >= valid_from)
);
CREATE INDEX line_route_mappings_line_idx ON public.line_route_mappings(line_id,status);
CREATE INDEX line_route_mappings_route_idx ON public.line_route_mappings(feed_version_id,route_id);
CREATE INDEX line_route_mappings_pattern_idx ON public.line_route_mappings(feed_version_id,route_id,pattern_id);
